# Request-ID propagation middleware (SQB-11)
#
# Reads the inbound `X-Request-ID` header — generated by Service.AI's
# Fastify request id — and echoes it back on the response. When the
# header is absent (direct admin calls, anonymous probes) a UUIDv4
# is generated. The id is also attached to `request.state.request_id`
# so route handlers can include it in log statements; one id traces
# the full chain web → Service.AI → BC AI Agent → BC OData.
class RequestIdMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request: Request, call_next):
        import uuid
        rid = request.headers.get("x-request-id") or str(uuid.uuid4())
        request.state.request_id = rid
        response = await call_next(request)
        response.headers["X-Request-ID"] = rid
        return response


# Public-path CORS middleware — allow any origin for /api/public/* (widget embeds)
class PublicCORSMiddleware(BaseHTTPMiddleware):
    """Open CORS for /api/public/ so the widget works from any embedding site."""
    async def dispatch(self, request: Request, call_next):
        if request.url.path.startswith("/api/public/"):
            origin = request.headers.get("origin", "*")
            if request.method == "OPTIONS":
                return Response(
                    status_code=200,
                    headers={
                        "Access-Control-Allow-Origin": origin,
                        "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
                        "Access-Control-Allow-Headers": "Content-Type",
                        "Access-Control-Max-Age": "86400",
                    },
                )
            response = await call_next(request)
            response.headers["Access-Control-Allow-Origin"] = origin
            response.headers["Access-Control-Allow-Methods"] = "GET, POST, OPTIONS"
            response.headers["Access-Control-Allow-Headers"] = "Content-Type"
            return response
        return await call_next(request)

# CORS middleware — origins come from ALLOWED_ORIGINS env var
app.add_middleware(
    CORSMiddleware,
    allow_origins=[o.strip() for o in settings.ALLOWED_ORIGINS.split(",") if o.strip()],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Public CORS must be added AFTER CORSMiddleware (runs first in reverse order)
# so it intercepts /api/public/ requests before the restricted CORS middleware
app.add_middleware(PublicCORSMiddleware)

# Request-ID is the outermost middleware so every other layer (CORS,
# auth, routers) sees `request.state.request_id` populated. Add it
# LAST so it wraps everything else (Starlette middleware order is
# inverse-registration: last-added is the outermost wrapper).
app.add_middleware(RequestIdMiddleware)

