@asynccontextmanager
async def lifespan(app: FastAPI):
    """Application lifespan events"""
    # Startup
    logger.info("=" * 80)
    logger.info("BC AI Agent starting up...")
    logger.info("Phase 1: Email quote parsing + Quote generation")
    logger.info("=" * 80)

    # TODO: Initialize database connection
    # TODO: Initialize BC API client
    # TODO: Initialize Graph API client
    # TODO: Initialize Anthropic client

    # Start scheduled email monitoring — only in ONE Gunicorn worker.
    # With -w 4, each worker runs lifespan independently. Use a file lock
    # so only the first worker starts the scheduler; the rest skip it.
    import os
    _scheduler_lock = "/tmp/bc_scheduler_lock"
    _owns_scheduler = False
    if settings.ENABLE_EMAIL_MONITORING:
        try:
            fd = os.open(_scheduler_lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
            os.write(fd, str(os.getpid()).encode())
            os.close(fd)
            _owns_scheduler = True
            scheduler = get_scheduler()
            scheduler.start(email_check_interval_minutes=settings.EMAIL_CHECK_INTERVAL_MINUTES)
            logger.info(f"✓ Scheduler started in worker PID {os.getpid()} (every {settings.EMAIL_CHECK_INTERVAL_MINUTES} min)")
        except FileExistsError:
            logger.info(f"Scheduler already running in another worker — skipping in PID {os.getpid()}")
        except Exception as e:
            logger.error(f"Failed to start scheduler: {e}", exc_info=True)
    else:
        logger.info("Email monitoring disabled (ENABLE_EMAIL_MONITORING=False)")

    # Initial BC sales-order sync — only run in the worker that owns the
    # scheduler lock, so we don't hammer BC with 4× the API calls under
    # Gunicorn. Done as an `await` here because lifespan is already inside
    # the asyncio event loop (asyncio.run can't nest).
    if _owns_scheduler:
        try:
            from app.services.bc_sync_service import bc_sync_service
            from app.db.database import SessionLocal as _SessionLocal
            _db = _SessionLocal()
            try:
                _stats = await bc_sync_service.sync_open_sales_orders_fast(_db)
                logger.info(
                    f"✓ Initial sales-order sync: {_stats.get('orders_synced', 0)} new, "
                    f"{_stats.get('orders_updated', 0)} updated, "
                    f"{len(_stats.get('errors', []))} errors"
                )
            finally:
                _db.close()
        except Exception as _sync_err:
            logger.error(f"Initial sales-order sync failed (non-fatal): {_sync_err}", exc_info=True)

    yield

    # Shutdown
    logger.info("=" * 80)
    logger.info("BC AI Agent shutting down...")
    logger.info("=" * 80)

    # Stop background scheduler (only in the worker that owns it)
    if _owns_scheduler:
        try:
            scheduler = get_scheduler()
            scheduler.stop()
            logger.info("Scheduler stopped")
            os.unlink(_scheduler_lock)
        except Exception as e:
            logger.error(f"Error stopping scheduler: {e}", exc_info=True)

    # TODO: Close database connections


